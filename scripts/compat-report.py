"""Render docs/COMPATIBILITY.md from a self-test report (reports/selftest.json).

Usage: compat-report.py reports/selftest.json > docs/COMPATIBILITY.md
"""
import json
import sys

MARK = {"pass": "✅", "fail": "❌", "skip": "–", "known": "⚠️"}


def main():
    doc = json.load(open(sys.argv[1]))
    res = doc["results"]
    out = []
    w = out.append
    counts = doc["counts"]
    w("# Compatibility\n")
    w("Generated by `scripts/compat-report.py` from the self-test report of %s "
      "(Linux %s). %s.\n" % (doc["started"], doc["kernel"],
                             ", ".join("%d %s" % (v, k) for k, v in sorted(counts.items()))))
    w("✅ pass · ❌ fail · ⚠️ known difference ([tests/known-differences.tsv](../tests/known-differences.tsv)) · "
      "– skipped: the stack lacks the capability (never counted as a pass).\n")
    w("## Images\n")
    w("| Adapter | Upstream | Version | Revision |\n|---|---|---|---|")
    for a, v in sorted(doc["versions"].items()):
        w("| %s | %s | %s | `%s` |" % (a, v.get("upstream", ""), v.get("version", ""), v.get("revision", "")[:12]))
    w("")

    for suite, title in (("raw", "Raw CAN (sender → receiver)"), ("isotp", "ISO-TP (sender → receiver)")):
        rows = [r for r in res if r["suite"] == suite and r["sender"] and r["receiver"] and "+" not in r["receiver"]]
        pairs = sorted({(r["sender"], r["receiver"]) for r in rows})
        scenarios = []
        for r in rows:
            if r["scenario"] not in scenarios:
                scenarios.append(r["scenario"])
        w("## %s\n" % title)
        w("| Scenario | " + " | ".join("%s → %s" % p for p in pairs) + " |")
        w("|---|" + "---|" * len(pairs))
        for sc in scenarios:
            cells = []
            for p in pairs:
                m = [r for r in rows if r["scenario"] == sc and (r["sender"], r["receiver"]) == p]
                cells.append(" ".join(MARK[r["status"]] for r in m) if m else "")
            w("| %s | %s |" % (sc, " | ".join(cells)))
        w("")

    other = [r for r in res if not (r["sender"] and r["receiver"] and "+" not in r["receiver"]) or r["suite"] == "dbc"]
    w("## Other scenarios\n")
    w("| Suite | Scenario | Stacks | Result | Detail |\n|---|---|---|---|---|")
    for r in other:
        stacks = " → ".join(x for x in (r["sender"], r["receiver"]) if x)
        w("| %s | %s | %s | %s | %s |" % (r["suite"], r["scenario"], stacks, MARK[r["status"]],
                                          r["detail"].replace("|", "\\|")[:160]))
    w("")
    fails = [r for r in res if r["status"] == "fail"]
    if fails:
        w("## Failures\n")
        for r in fails:
            w("* %s %s %s → %s: %s" % (r["suite"], r["scenario"], r["sender"], r["receiver"], r["detail"][:300]))
        w("")
    print("\n".join(out))


if __name__ == "__main__":
    main()
